#[test]
fn batch3_catalog_is_complete() {
    let entries: Vec<_> = catalog().collect();
    let names: Vec<_> = entries.iter().map(|info| info.name).collect();
    assert!(names.len() >= BATCH3.len());
    assert_eq!(&names[names.len() - BATCH3.len()..], &BATCH3);
    for (name, info) in BATCH3.iter().zip(&entries[entries.len() - BATCH3.len()..]) {
        assert!(create(name, 48_000.0).is_some(), "failed to create {name}");
        assert!(
            create_with_seed(name, 44_100.0, 1).is_some(),
            "failed to create {name} with seed"
        );
        assert_eq!(info.upstream_name, *name);
    }
}
