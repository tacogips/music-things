#[test]
fn batch1_catalog_is_complete() {
    let entries: Vec<_> = catalog().collect();
    let names: Vec<_> = entries.iter().map(|info| info.name).collect();
    assert_eq!(&names[..BATCH1.len()], &BATCH1[..]);
    let mapped = entries
        .iter()
        .find(|info| info.name == "Console8BusOut")
        .unwrap();
    assert_eq!(mapped.upstream_name, "Console8BussOut");
    for name in BATCH1 {
        assert!(create(name, 48_000.0).is_some(), "failed to create {name}");
    }
}
